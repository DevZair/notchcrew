import AppKit
import ImageIO
import Darwin

/// Main-thread clipboard history. Persistence is opt-in through an explicit local
/// storage URL; existing clipboard contents are never imported on startup/resume.
final class OfficeClipboard {
    struct Entry {
        let id: UUID
        let text: String
        let date: Date
        let imageData: Data?
        let thumbnailData: Data?
        let imageWidth: Int
        let imageHeight: Int
        var isImage: Bool { imageData != nil }

        init(id: UUID, text: String, date: Date, imageData: Data? = nil,
             thumbnailData: Data? = nil, imageWidth: Int = 0, imageHeight: Int = 0) {
            self.id = id; self.text = text; self.date = date
            self.imageData = imageData; self.thumbnailData = thumbnailData
            self.imageWidth = imageWidth; self.imageHeight = imageHeight
        }
        fileprivate var byteCount: Int { text.utf8.count + (imageData?.count ?? 0) + (thumbnailData?.count ?? 0) }
    }

    private struct StoredEntry: Codable {
        let id: UUID
        let text: String
        let date: Date
        let imageData: Data?
    }
    private struct Store: Codable {
        let version: Int
        let paused: Bool
        let entries: [StoredEntry]
    }
    private enum StorageError: Error { case unsafePath, io, invalid }
    private struct ImagePayload {
        let full: Data
        let thumbnail: Data
        let width: Int
        let height: Int
    }

    private(set) var entries: [Entry] = []
    private(set) var isPaused = false
    private(set) var lastError: String?
    var onChange: (() -> Void)?

    private let pasteboard: NSPasteboard
    private let now: () -> Date
    private let useRuntimeTimer: Bool
    private let storageURL: URL?
    private var persistenceBlocked = false
    private var timer: Timer?
    private var isStarted = false
    private var observedChangeCount: Int
    private static let maximumEntries = 30
    private static let maximumTextBytes = 64 * 1024
    private static let maximumSourceBytes = 16 * 1024 * 1024
    private static let maximumImageBytes = 8 * 1024 * 1024
    private static let maximumHistoryBytes = 48 * 1024 * 1024
    private static let maximumStoreBytes = 52 * 1024 * 1024
    private static let excludedTypes: Set<String> = [
        "org.nspasteboard.concealedtype", "org.nspasteboard.transienttype",
        "org.nspasteboard.autogeneratedtype", "org.nspasteboard.confidentialtype",
        "com.agilebits.onepassword", "com.apple.pasteboard.concealedtype",
        "de.petermaurer.transientpasteboardtype",
    ]

    init(pasteboard: NSPasteboard = .general,
         now: @escaping () -> Date = Date.init,
         useRuntimeTimer: Bool = true,
         storageURL: URL? = nil) {
        self.pasteboard = pasteboard
        self.now = now
        self.useRuntimeTimer = useRuntimeTimer
        self.storageURL = storageURL
        observedChangeCount = pasteboard.changeCount
        restore()
    }

    func start() {
        precondition(Thread.isMainThread)
        guard !isStarted else { return }
        isStarted = true
        observedChangeCount = pasteboard.changeCount
        if useRuntimeTimer {
            let timer = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in self?.poll() }
            self.timer = timer
            RunLoop.main.add(timer, forMode: .common)
        }
        onChange?()
    }

    func stop() {
        precondition(Thread.isMainThread)
        isStarted = false
        timer?.invalidate()
        timer = nil
        observedChangeCount = pasteboard.changeCount
    }

    func setPaused(_ paused: Bool) {
        precondition(Thread.isMainThread)
        guard isPaused != paused else { return }
        isPaused = paused
        observedChangeCount = pasteboard.changeCount
        changed()
    }

    func clear() {
        precondition(Thread.isMainThread)
        observedChangeCount = pasteboard.changeCount
        // Explicit clear also authorizes replacing a corrupt history file.
        let needsChange = !entries.isEmpty || lastError != nil
        entries.removeAll()
        persistenceBlocked = false
        if needsChange { changed() }
    }

    @discardableResult
    func copy(id: UUID) -> Bool {
        precondition(Thread.isMainThread)
        guard let entry = entries.first(where: { $0.id == id }) else { return false }
        let ownChangeCount = pasteboard.clearContents()
        let copied: Bool
        if let imageData = entry.imageData {
            copied = pasteboard.setData(imageData, forType: .png)
        } else {
            copied = pasteboard.setString(entry.text, forType: .string)
        }
        // Only suppress our own generation, never a later concurrent copy.
        observedChangeCount = ownChangeCount
        return copied
    }

    func remove(id: UUID) {
        precondition(Thread.isMainThread)
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        entries.remove(at: index)
        changed()
    }

    /// Internal entry point used by deterministic named-pasteboard tests.
    func poll() {
        precondition(Thread.isMainThread)
        guard isStarted else { return }
        let changeCount = pasteboard.changeCount
        guard changeCount != observedChangeCount else { return }
        observedChangeCount = changeCount
        guard !isPaused else { return }
        let types = (pasteboard.types ?? []) + (pasteboard.pasteboardItems ?? []).flatMap(\.types)
        guard !types.contains(where: { Self.isExcluded($0.rawValue) }) else { return }

        var image: ImagePayload?
        var text = ""
        if let imageType = [NSPasteboard.PasteboardType.png, .tiff].first(where: { types.contains($0) }) {
            guard let data = pasteboard.data(forType: imageType), let decoded = Self.decodeImage(data) else { return }
            image = decoded
        } else {
            guard let data = pasteboard.data(forType: .string), data.count <= Self.maximumTextBytes,
                  let value = String(data: data, encoding: .utf8),
                  !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
            text = value
        }
        guard pasteboard.changeCount == changeCount else { return }
        let same: (Entry) -> Bool = { entry in
            if let image { return entry.imageData == image.full }
            return !entry.isImage && entry.text == text
        }
        let previous = entries.first(where: same)
        entries.removeAll(where: same)
        entries.insert(Entry(id: previous?.id ?? UUID(), text: text, date: now(),
                             imageData: image?.full, thumbnailData: image?.thumbnail,
                             imageWidth: image?.width ?? 0, imageHeight: image?.height ?? 0), at: 0)
        while entries.count > Self.maximumEntries || entries.reduce(0, { $0 + $1.byteCount }) > Self.maximumHistoryBytes {
            entries.removeLast()
        }
        changed()
    }

    private func changed() {
        persist()
        onChange?()
    }

    private static func isExcluded(_ type: String) -> Bool {
        let normalized = type.lowercased()
        return excludedTypes.contains(normalized) || normalized.contains("confidential")
            || normalized.contains("concealed") || normalized.contains("transient")
            || normalized.contains("autogenerated")
    }

    private static func png(_ image: CGImage) -> Data? {
        let data = NSMutableData()
        guard let output = CGImageDestinationCreateWithData(data, "public.png" as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(output, image, nil)
        guard CGImageDestinationFinalize(output) else { return nil }
        return data as Data
    }

    private static func decodeImage(_ data: Data, restoringCanonicalPNG: Bool = false) -> ImagePayload? {
        guard !data.isEmpty, data.count <= maximumSourceBytes,
              let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
              let actualType = CGImageSourceGetType(source) as String?,
              ["public.png", "public.tiff"].contains(actualType),
              !restoringCanonicalPNG || actualType == "public.png",
              CGImageSourceGetCount(source) == 1,
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              (1...8192).contains(width), (1...8192).contains(height), width * height <= 20_000_000,
              let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceCreateThumbnailWithTransform: true,
                kCGImageSourceThumbnailMaxPixelSize: max(width, height),
              ] as CFDictionary),
              (1...8192).contains(image.width), (1...8192).contains(image.height),
              image.width * image.height <= 20_000_000 else { return nil }
        let orientation = properties[kCGImagePropertyOrientation] as? Int ?? 1
        let fullData = restoringCanonicalPNG && orientation == 1 ? data : png(image)
        guard let full = fullData, full.count <= maximumImageBytes,
              let canonicalSource = CGImageSourceCreateWithData(full as CFData, nil),
              let thumbnail = CGImageSourceCreateThumbnailAtIndex(canonicalSource, 0, [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceCreateThumbnailWithTransform: true,
                kCGImageSourceThumbnailMaxPixelSize: 256,
              ] as CFDictionary), let thumbnailData = png(thumbnail) else { return nil }
        return ImagePayload(full: full, thumbnail: thumbnailData, width: image.width, height: image.height)
    }

    /// Walk each directory via descriptors so neither directory nor final-file
    /// symlinks are followed. Only newly created directories and the final private
    /// history directory have their permissions changed.
    private func openStorageDirectory() throws -> (Int32, String) {
        guard let storageURL, storageURL.isFileURL else { throw StorageError.unsafePath }
        let path = storageURL.path
        guard path.hasPrefix("/"), !path.contains("\0") else { throw StorageError.unsafePath }
        let components = path.split(separator: "/").map(String.init)
        guard components.count >= 2, components.allSatisfy({ $0 != "." && $0 != ".." }),
              let filename = components.last else { throw StorageError.unsafePath }
        var directory = Darwin.open("/", O_RDONLY | O_DIRECTORY | O_CLOEXEC)
        guard directory >= 0 else { throw StorageError.io }
        do {
            for component in components.dropLast() {
                if mkdirat(directory, component, 0o700) != 0 && errno != EEXIST { throw StorageError.io }
                let next = openat(directory, component, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
                guard next >= 0 else { throw StorageError.unsafePath }
                Darwin.close(directory)
                directory = next
            }
            var info = stat()
            guard fstat(directory, &info) == 0, info.st_uid == getuid(), fchmod(directory, 0o700) == 0 else { throw StorageError.unsafePath }
            return (directory, filename)
        } catch {
            Darwin.close(directory)
            throw error
        }
    }

    private func restore() {
        guard storageURL != nil else { return }
        do {
            let (directory, filename) = try openStorageDirectory()
            defer { Darwin.close(directory) }
            let file = openat(directory, filename, O_RDONLY | O_NOFOLLOW | O_CLOEXEC | O_NONBLOCK)
            if file < 0 && errno == ENOENT { return }
            guard file >= 0 else { throw StorageError.unsafePath }
            defer { Darwin.close(file) }
            var info = stat()
            guard fstat(file, &info) == 0, (info.st_mode & S_IFMT) == S_IFREG,
                  info.st_uid == getuid(), info.st_nlink == 1,
                  info.st_size > 0, info.st_size <= Self.maximumStoreBytes,
                  fchmod(file, 0o600) == 0 else { throw StorageError.invalid }
            var data = Data(count: Int(info.st_size))
            let readOK = data.withUnsafeMutableBytes { buffer -> Bool in
                var offset = 0
                while offset < buffer.count {
                    let count = Darwin.read(file, buffer.baseAddress!.advanced(by: offset), buffer.count - offset)
                    if count < 0 && errno == EINTR { continue }
                    guard count > 0 else { return false }
                    offset += count
                }
                return true
            }
            guard readOK else { throw StorageError.io }
            let stored = try PropertyListDecoder().decode(Store.self, from: data)
            guard stored.version == 1, stored.entries.count <= Self.maximumEntries else { throw StorageError.invalid }
            var restored: [Entry] = []
            var ids = Set<UUID>()
            var total = 0
            for item in stored.entries {
                guard ids.insert(item.id).inserted, item.date.timeIntervalSince1970.isFinite,
                      (0...4_102_444_800).contains(item.date.timeIntervalSince1970),
                      item.text.utf8.count <= Self.maximumTextBytes else { throw StorageError.invalid }
                let image: ImagePayload?
                if let data = item.imageData {
                    guard data.count <= Self.maximumImageBytes, let decoded = Self.decodeImage(data, restoringCanonicalPNG: true), item.text.isEmpty else { throw StorageError.invalid }
                    image = decoded
                } else {
                    guard !item.text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { throw StorageError.invalid }
                    image = nil
                }
                let entry = Entry(id: item.id, text: item.text, date: item.date,
                                  imageData: image?.full, thumbnailData: image?.thumbnail,
                                  imageWidth: image?.width ?? 0, imageHeight: image?.height ?? 0)
                total += entry.byteCount
                guard total <= Self.maximumHistoryBytes else { throw StorageError.invalid }
                restored.append(entry)
            }
            entries = restored
            isPaused = stored.paused
        } catch {
            persistenceBlocked = true
            lastError = "Не удалось прочитать историю. Файл сохранён; очистите историю, чтобы начать заново."
        }
    }

    private func persist() {
        guard storageURL != nil, !persistenceBlocked else { return }
        do {
            let stored = Store(version: 1, paused: isPaused, entries: entries.map {
                StoredEntry(id: $0.id, text: $0.text, date: $0.date, imageData: $0.imageData)
            })
            let encoder = PropertyListEncoder()
            encoder.outputFormat = .binary
            let data = try encoder.encode(stored)
            guard data.count <= Self.maximumStoreBytes else { throw StorageError.invalid }
            let (directory, filename) = try openStorageDirectory()
            defer { Darwin.close(directory) }
            var existing = stat()
            if fstatat(directory, filename, &existing, AT_SYMLINK_NOFOLLOW) == 0 {
                guard (existing.st_mode & S_IFMT) == S_IFREG, existing.st_uid == getuid(), existing.st_nlink == 1 else { throw StorageError.unsafePath }
            } else if errno != ENOENT { throw StorageError.io }
            let temporary = ".clipboard-\(UUID().uuidString).tmp"
            let file = openat(directory, temporary, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, 0o600)
            guard file >= 0 else { throw StorageError.io }
            defer { Darwin.close(file); unlinkat(directory, temporary, 0) }
            let wrote = data.withUnsafeBytes { buffer -> Bool in
                var offset = 0
                while offset < buffer.count {
                    let count = Darwin.write(file, buffer.baseAddress!.advanced(by: offset), buffer.count - offset)
                    if count < 0 && errno == EINTR { continue }
                    guard count > 0 else { return false }
                    offset += count
                }
                return true
            }
            guard wrote, fsync(file) == 0,
                  renameat(directory, temporary, directory, filename) == 0 else { throw StorageError.io }
            lastError = nil
        } catch {
            lastError = "Не удалось сохранить изменения. После перезапуска может вернуться прежняя история."
        }
    }

    deinit { timer?.invalidate() }
}
