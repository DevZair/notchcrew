import AppKit
import ImageIO

@main
struct ClipboardTests {
    static func main() {
        let pasteboard = NSPasteboard(name: .init("OfficeClipboardTests-\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        func write(_ text: String, marker: String? = nil) {
            pasteboard.clearContents()
            precondition(pasteboard.setString(text, forType: .string))
            if let marker { precondition(pasteboard.setData(Data(), forType: .init(marker))) }
        }

        write("existing clipboard must not be read")
        var date = Date(timeIntervalSince1970: 1_000)
        let history = OfficeClipboard(pasteboard: pasteboard, now: { date }, useRuntimeTimer: false)
        var changes = 0
        history.onChange = { changes += 1 }
        history.start()
        changes = 0
        history.poll()
        precondition(history.entries.isEmpty && changes == 0)

        write("First\nline")
        history.poll()
        precondition(history.entries.count == 1 && history.entries[0].text == "First\nline")
        precondition(history.entries[0].date == date && changes == 1)
        history.poll()
        history.start()
        history.poll()
        precondition(changes == 1)
        let firstID = history.entries[0].id
        write("Second 🐈")
        history.poll()
        date.addTimeInterval(10)
        write("First\nline")
        history.poll()
        precondition(history.entries.count == 2 && history.entries[0].id == firstID)
        precondition(history.entries[0].date == date)
        let beforeOwnCopy = changes
        precondition(history.copy(id: history.entries[1].id))
        precondition(pasteboard.string(forType: .string) == "Second 🐈")
        history.poll()
        precondition(changes == beforeOwnCopy && history.entries[0].id == firstID)
        precondition(!history.copy(id: UUID()))

        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType", "org.nspasteboard.ConfidentialType",
                       "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
                       "com.vendor.CONFIDENTIAL"] {
            write("must skip \(marker)", marker: marker)
            history.poll()
        }
        precondition(history.entries.count == 2 && changes == beforeOwnCopy)
        // Any private item suppresses the whole copy, even when another item is plain text.
        pasteboard.clearContents()
        let plain = NSPasteboardItem()
        plain.setString("Public-looking text", forType: .string)
        let secret = NSPasteboardItem()
        secret.setData(Data(), forType: .init("org.nspasteboard.ConcealedType"))
        precondition(pasteboard.writeObjects([plain, secret]))
        history.poll()
        precondition(changes == beforeOwnCopy)
        write(" \n\t")
        history.poll()
        write(String(repeating: "a", count: 65_537))
        history.poll()
        write(String(repeating: "🐈", count: 16_385))
        history.poll()
        precondition(changes == beforeOwnCopy)
        write(String(repeating: "🐈", count: 16_384))
        history.poll()
        precondition(history.entries.first?.text.utf8.count == 65_536)

        history.setPaused(true)
        write("Paused")
        history.poll()
        write("Paused, not polled")
        history.setPaused(false)
        history.poll()
        precondition(!history.entries.contains(where: { $0.text.hasPrefix("Paused") }))
        history.stop()
        write("Stopped")
        history.poll()
        history.start()
        history.poll()
        precondition(!history.entries.contains(where: { $0.text == "Stopped" }))

        for index in 0..<35 {
            write("Entry \(index)")
            history.poll()
        }
        precondition(history.entries.count == 30)
        precondition(history.entries.first?.text == "Entry 34" && history.entries.last?.text == "Entry 5")
        let removed = history.entries[4].id
        history.remove(id: removed)
        precondition(history.entries.count == 29 && !history.entries.contains(where: { $0.id == removed }))
        let beforeMissingRemoval = changes
        history.remove(id: UUID())
        precondition(changes == beforeMissingRemoval)
        write("Pending before clear")
        history.clear()
        history.poll()
        precondition(history.entries.isEmpty)
        precondition(pasteboard.string(forType: .string) == "Pending before clear", "Clear must not overwrite system clipboard")

        // Real timer uses an isolated pasteboard only, and releases its owner.
        weak var weakHistory: OfficeClipboard?
        autoreleasepool {
            let timed = OfficeClipboard(pasteboard: pasteboard)
            weakHistory = timed
            timed.start()
            write("Timer-only entry")
            RunLoop.main.run(until: Date().addingTimeInterval(0.9))
            precondition(timed.entries.first?.text == "Timer-only entry")
        }
        precondition(weakHistory == nil, "Timer retained history")
        persistentImages(pasteboard: pasteboard)
        print("Clipboard checks passed: startup/resume privacy, timer cleanup, private markers, UTF-8 bounds, deduplication, copy, remove, clear, retention")
    }

    static func imageData(width: Int = 400, height: Int = 300, type: String = "public.png", orientation: Int = 1) -> Data {
        let context = CGContext(data: nil, width: width, height: height, bitsPerComponent: 8,
                                bytesPerRow: width * 4, space: CGColorSpaceCreateDeviceRGB(),
                                bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
        context.setFillColor(CGColor(red: 0.3, green: 0.7, blue: 0.5, alpha: 1))
        context.fill(CGRect(x: 0, y: 0, width: width, height: height))
        let data = NSMutableData()
        let destination = CGImageDestinationCreateWithData(data, type as CFString, 1, nil)!
        CGImageDestinationAddImage(destination, context.makeImage()!, [kCGImagePropertyOrientation: orientation] as CFDictionary)
        precondition(CGImageDestinationFinalize(destination))
        return data as Data
    }

    static func persistentImages(pasteboard: NSPasteboard) {
        let fm = FileManager.default
        // Foundation normalizes /private/var back to /var while resolving URLs;
        // our secure store intentionally refuses that symlink, so use its real path.
        let temporaryPath = fm.temporaryDirectory.path
        let realTemporary = temporaryPath.hasPrefix("/var/") ? "/private" + temporaryPath : temporaryPath
        let directory = URL(fileURLWithPath: realTemporary).appendingPathComponent("OfficeClipboardTests-\(UUID().uuidString)")
        let url = directory.appendingPathComponent("history.plist")
        defer { try? fm.removeItem(at: directory) }
        func make(_ storage: URL? = nil) -> OfficeClipboard {
            OfficeClipboard(pasteboard: pasteboard, useRuntimeTimer: false, storageURL: storage ?? url)
        }
        func text(_ value: String, to history: OfficeClipboard) {
            pasteboard.clearContents()
            precondition(pasteboard.setString(value, forType: .string))
            history.poll()
        }
        let history = make()
        precondition(history.lastError == nil)
        history.start()
        text("Saved text", to: history)
        precondition(history.lastError == nil && fm.fileExists(atPath: url.path))
        let attributes = try! fm.attributesOfItem(atPath: url.path)
        let directoryAttributes = try! fm.attributesOfItem(atPath: directory.path)
        precondition((attributes[.posixPermissions] as? NSNumber)?.intValue == 0o600)
        precondition((directoryAttributes[.posixPermissions] as? NSNumber)?.intValue == 0o700)
        let png = imageData()
        pasteboard.clearContents()
        precondition(pasteboard.setData(png, forType: .png))
        precondition(pasteboard.setString("Image fallback text must not capture", forType: .string))
        history.poll()
        let picture = history.entries[0]
        precondition(picture.isImage && picture.text.isEmpty && picture.imageWidth == 400 && picture.imageHeight == 300)
        let thumb = CGImageSourceCreateWithData(picture.thumbnailData! as CFData, nil)!
        let thumbImage = CGImageSourceCreateImageAtIndex(thumb, 0, nil)!
        precondition(thumbImage.width == 256 && thumbImage.height == 192)
        precondition(history.copy(id: picture.id))
        precondition(pasteboard.data(forType: .png) == picture.imageData)
        history.poll()
        precondition(history.entries.count == 2)
        history.setPaused(true)
        let restored = make()
        precondition(restored.lastError == nil && restored.isPaused)
        precondition(restored.entries.map(\.id) == history.entries.map(\.id))
        precondition(restored.entries[0].imageData == picture.imageData && restored.entries[0].imageWidth == 400)
        precondition(restored.entries[1].text == "Saved text")
        restored.start()
        restored.setPaused(false)
        pasteboard.clearContents()
        precondition(pasteboard.setData(imageData(type: "public.tiff", orientation: 6), forType: .tiff))
        restored.poll()
        precondition(restored.entries[0].imageWidth == 300 && restored.entries[0].imageHeight == 400, "TIFF orientation must normalize full-resolution pixels")
        precondition(restored.entries[0].isImage)
        let normalized = restored.entries[0].imageData
        precondition(make().entries[0].imageData == normalized)
        let beforeInvalid = restored.entries.count
        for invalid in [Data("invalid image".utf8), Data(repeating: 1, count: 16 * 1024 * 1024 + 1), imageData(width: 8193, height: 1)] {
            pasteboard.clearContents()
            precondition(pasteboard.setData(invalid, forType: .png))
            restored.poll()
        }
        pasteboard.clearContents()
        precondition(pasteboard.setData(png, forType: .png))
        precondition(pasteboard.setData(Data(), forType: .init("org.nspasteboard.ConcealedType")))
        restored.poll()
        precondition(restored.entries.count == beforeInvalid)
        restored.remove(id: picture.id)
        precondition(!make().entries.contains(where: { $0.id == picture.id }))
        restored.clear()
        precondition(make().entries.isEmpty)

        // Corrupt and structurally invalid stores are preserved until explicit clear.
        let corrupt = Data("not a plist".utf8)
        try! corrupt.write(to: url)
        let broken = make()
        precondition(broken.lastError != nil && broken.entries.isEmpty)
        broken.start()
        text("Memory-only while broken", to: broken)
        precondition(try! Data(contentsOf: url) == corrupt)
        broken.clear()
        precondition(broken.lastError == nil && make().entries.isEmpty)
        let invalidEntry: [String: Any] = ["id": UUID().uuidString, "text": "", "date": Date(), "imageData": Data([1, 2, 3])]
        let invalidStore: [String: Any] = ["version": 1, "paused": false, "entries": [invalidEntry]]
        let invalidData = try! PropertyListSerialization.data(fromPropertyList: invalidStore, format: .binary, options: 0)
        try! invalidData.write(to: url)
        precondition(make().lastError != nil)
        make().clear()
        let validEntry: [String: Any] = ["id": UUID().uuidString, "text": "valid", "date": Date()]
        var invalidID = validEntry
        invalidID["id"] = "not-a-uuid"
        var invalidDate = validEntry
        invalidDate["date"] = Date(timeIntervalSince1970: 5_000_000_000)
        var oversizedText = validEntry
        oversizedText["text"] = String(repeating: "x", count: 65_537)
        let rejectedStores: [[String: Any]] = [
            ["version": 99, "paused": false, "entries": []],
            ["version": 1, "paused": false, "entries": [invalidID]],
            ["version": 1, "paused": false, "entries": [invalidDate]],
            ["version": 1, "paused": false, "entries": [oversizedText]],
            ["version": 1, "paused": false, "entries": [validEntry, validEntry]],
            ["version": 1, "paused": false, "entries": Array(repeating: validEntry, count: 31)],
        ]
        for store in rejectedStores {
            let data = try! PropertyListSerialization.data(fromPropertyList: store, format: .binary, options: 0)
            try! data.write(to: url)
            precondition(make().lastError != nil && make().entries.isEmpty)
        }
        make().clear()

        // A symlink at either the directory or file is rejected without touching its target.
        let target = directory.appendingPathComponent("target.txt")
        try! Data("preserve target".utf8).write(to: target)
        try! fm.removeItem(at: url)
        try! fm.createSymbolicLink(at: url, withDestinationURL: target)
        let linked = make()
        precondition(linked.lastError != nil)
        linked.clear()
        precondition(linked.lastError != nil && (try! String(contentsOf: target, encoding: .utf8)) == "preserve target")
        try! fm.removeItem(at: url)
        let linkDirectory = directory.appendingPathComponent("linked")
        try! fm.createSymbolicLink(at: linkDirectory, withDestinationURL: directory)
        precondition(make(linkDirectory.appendingPathComponent("history.plist")).lastError != nil)

        // Sparse oversized files fail before allocating or decoding their contents.
        precondition(fm.createFile(atPath: url.path, contents: Data()))
        let handle = try! FileHandle(forWritingTo: url)
        try! handle.truncate(atOffset: 52 * 1024 * 1024 + 1)
        try! handle.close()
        precondition(make().lastError != nil)
        make().clear()

        // A failed deletion save is visible and a later empty clear retries it.
        let retry = make()
        retry.start()
        text("Delete me", to: retry)
        try! fm.removeItem(at: url)
        try! fm.createDirectory(at: url, withIntermediateDirectories: false)
        retry.clear()
        precondition(retry.lastError != nil && retry.entries.isEmpty)
        try! fm.removeItem(at: url)
        retry.clear()
        precondition(retry.lastError == nil && make().entries.isEmpty)
        print("Persistent image checks passed: full-size PNG/TIFF orientation, thumbnails, restart, pause, private files, removal/clear, corruption preservation, symlinks, bounds, failed-save recovery")
    }
}
